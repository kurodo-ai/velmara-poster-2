#!/usr/bin/env python3
"""Hand in the Velmara travel poster: copy entry.png to the output dir.

The poster itself is generated by src/make_image.py (Pillow); the
rendered PNG is committed as entry.png, and this entrypoint — standard
library only — copies it to $MAKEFUN_OUTPUT_DIR (else /output).
"""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main() -> int:
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    src = os.path.join(HERE, "entry.png")
    if os.path.getsize(src) == 0:
        raise SystemExit("entry.png is empty")
    shutil.copyfile(src, os.path.join(out_dir, "entry.png"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
